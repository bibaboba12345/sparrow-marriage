"""Organ morphology classes → shared US findings (prompt once, map to catalog keys)."""

from __future__ import annotations

# Компактный блок для LLM: классы органов и общие состояния описываются ОДИН раз.
# Конкретные ключи всё равно только из каталога (Печень_увеличена, киста_яичника_R, …).

ORGAN_CLASSES_PROMPT = """
=== КЛАССЫ ОРГАНОВ И ОБЩИЕ СОСТОЯНИЯ (шаблон → ключ каталога) ===
Одинаковые УЗИ-находки повторяются у многих органов. Ниже — классы и состояния ОДИН раз.
Алгоритм: (1) определи орган и класс; (2) распознай состояние из списка;
(3) найди в КАТАЛОГЕ ключ вида <Орган>_<состояние> / <состояние>_<органа> / Киста*|Полип*|Узел*…
НЕ выдумывай ключ, если его нет в каталоге. Норма (ровные чёткие, однородный) → не ставь binary.

1) ПАРЕНХИМАТОЗНЫЕ / СОЛИДНЫЕ
   Органы: печень, поджелудочная, селезёнка, щитовидная (+доли/перешеек), простата,
   матка/миометрий, яичники R|L, молочная железа (паренхима), лимфоузлы.
   Общие состояния (ищи в каталоге для ЭТОГО органа):
   - увеличен(а/ы) / гепатомегалия / спленомегалия → *_увеличен(а/ы)
   - контуры неровные | нечёткие → *_контуры_неровные / *_контуры_нечеткие
   - паренхима / эхоструктура неоднородная | однородная → *_паренхима_неоднородная / *_неоднородный / *_однородный
   - эхогенность повышена | снижена | смешанная → *_эхогенность_*
   - диффузные изменения → диффузные_изменения_<органа>
   - размеры a×b×c / объём V → *_размеры_мм / *_объем_см3 / КВР_* (как в каталоге)
   - кровоток усилен (орган/ткань) → *_кровоток_усилен

2) ПОЛЫЕ / ТРУБЧАТЫЕ (полости, протоки, каналы; ЖП — гибрид: размер как solid + стенка/содержимое)
   Органы: желчный пузырь, холедох, вирсунгов проток, внутрипечёночные протоки,
   млечные протоки, полость матки, цервикальный канал, простатическая уретра, мочевой пузырь.
   Общие состояния:
   - расширен(а/ы) / дилатация → *_расширен(а/ы) / протоковая_система_расширена
   - диаметр N мм → *_диаметр_мм / *_расширение_мм
   - стенка утолщена | уплотнена | гиперэхогенна → *_стенка_*
   - содержимое (сладж, эховзвесь, анэхогенное) → *_содержимое_* / билиарный_сладж
   - деформирован(а) / перетяжка → *_деформирован(а)
   - конкремент / камень → конкременты_* / Конкремент*_мм (если есть в каталоге)

3) СОСУДЫ (артерии/вены)
   - проходимость, VPS, стеноз %, диаметр, расширена, тромбоз, рефлюкс, компрессия
   → ключи сосуда из каталога (не путай перфорантные вены с «перфорацией» органа).

4) ОЧАГОВЫЕ ОБРАЗОВАНИЯ (на любом органе класса 1–2)
   Состояния описывай ОДИН раз, привязывай к органу/стороне из текста:
   - киста → киста_<органа>[_R|_L] и/или Киста*_мм / Киста*_max_мм
   - полип → полип_<органа> / Полип*_мм
   - узел / очаг / объёмное образование → узел_* / Очаг* / *_очаговое_образование / Узел*_мм
   - кальцинат(ы) / микрокальцинаты → кальцинаты_* / Кальцинат*_мм
   Сторона R/L/bilat — как в правилах D/S выше. Размер очага → max сторона в мм.

Примеры раскрытия (если ключ есть в каталоге):
  «печень увеличена» → Печень_увеличена:1
  «киста правого яичника» → киста_яичника_R:1 (+ КистаЯичника_R_мм при размере)
  «холедох расширен до 8 мм» → Холедох_расширен:1 , Холедох_диаметр_мм:8
  «стенка ЖП утолщена» → ЖелчныйПузырь_стенка_утолщена:1
""".strip()


def organ_classes_prompt_block() -> str:
    return ORGAN_CLASSES_PROMPT
