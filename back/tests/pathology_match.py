def normalize_pathology(text: str) -> str:
    s = unicodedata.normalize("NFC", str(text or ""))
    s = _CAMEL.sub(r"\1 \2", s)
    s = s.lower().replace("ё", "е")
    s = s.replace("_", " ").replace("-", " ").replace("/", " ")
    s = re.sub(r"[^\w\s]+", " ", s, flags=re.UNICODE)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def words(text: str) -> set[str]:
    return set(_WORD_RE.findall(normalize_pathology(text)))


def humanize_token(token: str) -> str:
    return normalize_pathology(token)


def _side(ws: set[str]) -> str | None:
    if ws & _LEFT:
        return "L"
    if ws & _RIGHT:
        return "R"
    return None


def _synonym_hit(a: str, b: str) -> bool:
    na, nb = normalize_pathology(a), normalize_pathology(b)
    for group in _SYNONYM_GROUPS:
        if any(g in na or na in g for g in group) and any(g in nb or nb in g for g in group):
            return True
    return False


def pathologies_match(expected: str, found: str) -> bool:
    """True if expected and found name the same finding (not necessarily verbatim)."""
    e = normalize_pathology(expected)
    f = normalize_pathology(found)
    if not e or not f:
        return False
    if e == f:
        return True
    if e in f or f in e:
        return True
    if _synonym_hit(e, f):
        return True

    ew, fw = words(e), words(f)
    es, fs = _side(ew), _side(fw)
    if es and fs and es != fs:
        return False

    ew2, fw2 = ew - _STOP - _LEFT - _RIGHT, fw - _STOP - _LEFT - _RIGHT
    if not ew2 or not fw2:
        return False
    overlap = ew2 & fw2
    if len(overlap) >= 2 and len(overlap) / len(ew2) >= 0.5:
        return True
    if len(ew2) == 1 and ew2 <= fw2:
        return True
    # киста + яичник with compatible/missing side
    if {"киста", "яичника"} <= ew2 and {"киста", "яичника"} <= fw2:
        return es is None or fs is None or es == fs
    if {"киста", "яичник"} <= ew2 and ({"киста", "яичника"} <= fw2 or {"киста", "яичник"} <= fw2):
        return es is None or fs is None or es == fs
    # «фолликулярные кисты яичников» ≈ киста_яичника_R/L
    if ("фолликулярн" in e or "фолликулярн" in " ".join(ew2)) and (
        "кист" in e or any(w.startswith("кист") for w in ew2)
    ):
        if {"киста", "яичника"} <= fw2 or {"киста", "яичник"} <= fw2:
            return True
        if "яичник" in f and "кист" in f:
            return True
    # «кисты шейки матки» ≈ «киста шейки max мм» (есть размер = есть киста)
    if {"киста", "шейки"} <= ew2 or {"кисты", "шейки"} <= ew2:
        if {"киста", "шейки"} <= fw2 or {"кисты", "шейки"} <= fw2:
            return True
    return False


def cover_expected(expected_lines: list[str], found_labels: list[str]) -> tuple[list[str], list[str]]:
    """
    Return (missing, unmatched_found).
    expected `норма` → missing if any found; unmatched_found unused for pass/fail.
    """
    expected_lines = [x.strip() for x in expected_lines if x.strip()]
    found_labels = [x.strip() for x in found_labels if x.strip()]

    if expected_lines == ["норма"] or (
        len(expected_lines) == 1 and normalize_pathology(expected_lines[0]) == "норма"
    ):
        return (found_labels[:] if found_labels else [], [])

    missing: list[str] = []
    used: set[int] = set()
    for exp in expected_lines:
        hit = None
        for i, found in enumerate(found_labels):
            if i in used:
                continue
            if pathologies_match(exp, found):
                hit = i
                break
        if hit is None:
            if any(pathologies_match(exp, found) for found in found_labels):
                continue
            missing.append(exp)
        else:
            used.add(hit)
    unmatched = [found_labels[i] for i in range(len(found_labels)) if i not in used]
    return missing, unmatched
